#!/usr/bin/env bash
# Run the SysMonitor node agent as an unprivileged user (opt-in).
# Run from the repo root as root, after install.sh. Idempotent; backs up anything
# it replaces to *.bak-<timestamp>. Re-run after you change the monitored services
# (sudoers lists each service explicitly; the dashboard cannot widen it).
#
#   sudo contrib/install-nonroot.sh
#   contrib/install-nonroot.sh --print-sudoers [service ...]   # preview, no root needed
set -euo pipefail

SVC_USER="${SYSMON_USER:-sys-monitor}"
INSTALL_DIR="/opt/sys-monitor"
STATE_DIR="/var/lib/sys-monitor"
UNIT="/etc/systemd/system/sys-monitor.service"
SRC="$(cd "$(dirname "$0")" && pwd)"
STAMP="$(date +%Y%m%d-%H%M%S)"
ACTIONS=(start stop restart enable disable)
NAME_RE='^[A-Za-z0-9@._:-]+$'
USER_RE='^[a-z_][a-z0-9_-]*$'

die() { echo "error: $*" >&2; exit 1; }

# Absolute path of a command. Deliberately NOT symlink-resolved: on systemd hosts
# reboot and shutdown are symlinks to systemctl, and sudo matches commands by file
# identity, so every entry below must pin its arguments (see print_sudoers).
bin() {
  local p
  p="$(type -P "$1")" || die "$1 not found"
  printf '%s\n' "$p"
}

# sudoers treats , : = \ in arguments specially.
esc() { printf '%s' "$1" | sed 's/[,:=\\]/\\&/g'; }

# Monitored services: the persisted list wins, then the shipped default.
read_services() {
  local f
  for f in "$STATE_DIR/services.json" "$INSTALL_DIR/services.json"; do
    if [[ -f "$f" ]]; then
      python3 -c 'import json,sys; print("\n".join(json.load(open(sys.argv[1]))))' "$f"
      return
    fi
  done
  printf '%s\n' ssh nginx docker ollama mosquitto cron avahi-daemon
}

# One exact-match line per (action, service). A rule such as
# "systemctl start ssh nginx" only matches that exact argument string, and
# "systemctl *" would be root, so neither is used. reboot/shutdown are the same
# file as systemctl on systemd hosts, so a bare "NOPASSWD: /sbin/reboot" would let
# the user run ANY systemctl command as root: pin their arguments ("" = none).
print_sudoers() {
  local user="$1"
  shift
  [[ "$user" =~ $USER_RE ]] || die "invalid user name: $user"
  local systemctl reboot shutdown killbin svc act
  systemctl="$(bin systemctl)"
  reboot="$(bin reboot)"
  shutdown="$(bin shutdown)"
  killbin="$(bin kill)"
  echo "# /etc/sudoers.d/sys-monitor  (root:root 0440; generated by contrib/install-nonroot.sh)"
  echo "# Exactly the sudo calls sys_monitor.py makes; services are listed one by one."
  for svc in "$@"; do
    [[ "$svc" =~ $NAME_RE ]] || die "invalid service name: $svc"
    for act in "${ACTIONS[@]}"; do
      echo "$user ALL=(root) NOPASSWD: $systemctl $act $(esc "$svc")"
    done
  done
  echo "$user ALL=(root) NOPASSWD: $reboot \"\""
  echo "$user ALL=(root) NOPASSWD: $shutdown -h now"
  echo "$user ALL=(root) NOPASSWD: $killbin -9 *"
  echo "$user ALL=(root) NOPASSWD: $killbin -15 *"
}

backup() { if [[ -e "$1" ]]; then cp -a "$1" "$1.bak-$STAMP"; fi; }

main() {
  if [[ "${1:-}" == "--print-sudoers" ]]; then
    shift
    local svcs=("$@")
    if [[ ${#svcs[@]} -eq 0 ]]; then mapfile -t svcs < <(read_services); fi
    print_sudoers "$SVC_USER" "${svcs[@]}"
    return
  fi

  [[ $EUID -eq 0 ]] || die "run as root (sudo $0)"
  [[ -f "$UNIT" ]] || die "$UNIT not found: run install.sh first"
  [[ "$SVC_USER" =~ $USER_RE ]] || die "invalid user name: $SVC_USER"
  command -v visudo >/dev/null || die "visudo not found"

  if ! id "$SVC_USER" >/dev/null 2>&1; then
    useradd --system --no-create-home --home-dir /nonexistent \
      --shell /usr/sbin/nologin "$SVC_USER"
    echo "created service user $SVC_USER"
  fi

  # Everything the agent writes lives here, owned by the service user.
  install -d -o "$SVC_USER" -g "$SVC_USER" -m 0750 "$STATE_DIR"
  local f
  for f in services.json hiddenscope_allowlist.json hiddenscope_baseline.json; do
    if [[ -f "$INSTALL_DIR/$f" && ! -e "$STATE_DIR/$f" ]]; then
      install -o "$SVC_USER" -g "$SVC_USER" -m 0640 "$INSTALL_DIR/$f" "$STATE_DIR/$f"
      echo "copied $f to $STATE_DIR"
    fi
  done
  chown -R "$SVC_USER:$SVC_USER" "$STATE_DIR"

  # sudoers: validate before installing so a typo can never lock out sudo.
  local tmp svcs=()
  tmp="$(mktemp)"
  trap 'rm -f "$tmp"' EXIT
  mapfile -t svcs < <(read_services)
  print_sudoers "$SVC_USER" "${svcs[@]}" >"$tmp"
  visudo -cf "$tmp" >/dev/null || die "generated sudoers failed visudo; nothing installed"
  backup /etc/sudoers.d/sys-monitor
  install -o root -g root -m 0440 "$tmp" /etc/sudoers.d/sys-monitor

  install -d /etc/systemd/system/sys-monitor.service.d
  backup /etc/systemd/system/sys-monitor.service.d/nonroot.conf
  sed "s/^User=.*/User=$SVC_USER/" "$SRC/sys-monitor-nonroot.conf" \
    >/etc/systemd/system/sys-monitor.service.d/nonroot.conf
  chmod 0644 /etc/systemd/system/sys-monitor.service.d/nonroot.conf
  systemctl daemon-reload

  echo "Installed. Restart to switch: systemctl restart sys-monitor"
  echo "Then check: ps -o user= -p \$(systemctl show -p MainPID --value sys-monitor)"
  echo "To revert: delete sys-monitor.service.d/nonroot.conf and /etc/sudoers.d/sys-monitor, then daemon-reload and restart."
}

main "$@"
